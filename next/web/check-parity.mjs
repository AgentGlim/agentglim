// Usage: node check-parity.mjs [path-to-today-index.html] [--write]
// Lists each section of today's Observatory page as ported / missing / dropped (reason).
import { readFileSync, existsSync, writeFileSync, realpathSync, readdirSync, lstatSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const DEFAULT = join(here, 'fixtures/baseline-index.html');

export function check(pagePath = DEFAULT) {
  if (!existsSync(pagePath)) {
    throw new Error(`required baseline not found: ${pagePath}`);
  }
  const st = lstatSync(pagePath);
  if (st.isSymbolicLink()) {
    throw new Error(`baseline must not be a symlink: ${pagePath}`);
  }
  if (!st.isFile()) {
    throw new Error(`required baseline is not a regular file: ${pagePath}`);
  }
  const page = readFileSync(pagePath, 'utf8');
  const list = JSON.parse(readFileSync(join(here, 'fixtures/today-views.json'), 'utf8')).sections;
  const views = new Set(readdirSync(join(here, 'views')).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -3)));
  const rows = list.map((s) => {
    let status = s.status, note = s.reason ?? '';
    if (status === 'ported' && !views.has(s.view)) { status = 'missing'; note = `views/${s.view}.ts absent`; }
    const found = page.includes(s.probe);
    return { section: s.probe, view: s.view, status, note, found };
  });
  // sections in today's page that the list does not know
  const known = list.map((s) => s.probe);
  const h = [...page.matchAll(/<h[23][^>]*>([^<$]{3,60})/g)].map((m) => m[1].trim());
  for (const t of new Set(h)) {
    if (!known.some((k) => k.includes(t) || t.includes(k.replace('<h2>', '')))) rows.push({ section: t, view: null, status: 'missing', note: 'not in today-views.json', found: true });
  }
  // Validate required producers: every ported row must be present in the baseline markup.
  const bad = [];
  for (const s of list) {
    if (s.status !== 'ported') continue;
    const row = rows.find((r) => r.section === s.probe);
    if (!row || !row.found || row.status !== 'ported') {
      bad.push(`${s.probe} (view: ${s.view})`);
    }
  }
  if (bad.length) {
    throw new Error(`required producer missing: ${bad.join(', ')}`);
  }
  return { live: true, rows };
}

export function toMarkdown({ live, rows }) {
  const src = live ? 'read from `_observatory/index.html`' : '`_observatory/` absent: used checked-in `web/fixtures/today-views.json`';
  return `# Web parity (today's Observatory vs build/web)\n\nGenerated by \`node web/check-parity.mjs --write\`; ${src}.\n\n` +
    '| Section | View | Status | Note |\n|---|---|---|---|\n' +
    rows.map((r) => `| \`${r.section.replace(/\|/g, '/')}\` | ${r.view ?? '-'} | ${r.status === 'dropped' ? 'dropped (' + r.note + ')' : r.status} | ${r.status === 'dropped' ? '' : r.note} |`).join('\n') + '\n';
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const path = args.find((a) => !a.startsWith('--')) ?? DEFAULT;
  let res;
  try {
    res = check(path);
  } catch (e) {
    console.error(`error: ${e.message}`);
    process.exit(1);
  }
  if (!res.live) console.log(`note: ${path} absent, using web/fixtures/today-views.json`);
  const md = toMarkdown(res);
  console.log(md);
  if (args.includes('--write')) writeFileSync(join(here, '../docs/parity.md'), md);
  const missing = res.rows.filter((r) => r.status === 'missing');
  if (missing.length) { console.error(`${missing.length} missing`); process.exit(1); }
}
